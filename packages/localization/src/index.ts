export const messages: Record<Locale, Record<string, string>> = supportedLocales.reduce(
  (result, locale) => {
    result[locale] = { ...english, ...overrides[locale] };
    return result;
  },
  {} as Record<Locale, Record<string, string>>,
);

export function t(
  locale: Locale,
  key: string,
  parameters?: Record<string, string | number>,
): string {
  const message = messages[locale][key] ?? messages["en-US"][key] ?? key;
  return parameters
    ? Object.entries(parameters).reduce(
        (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
        message,
      )
    : message;
}
